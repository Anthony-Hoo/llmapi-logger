-- Organisation project reports (doc/features/23-org-project-reports.md).
-- Every table here is derived or management data: none is part of the
-- integrity event chain and none is copied by the SQLite offline importer.
-- Raw repository paths, remote URLs and working directories never appear in
-- plaintext; identity_enc holds them encrypted and the *_fpr columns are
-- keyed HMAC tags.
CREATE TABLE audit_project_identity (
    audit_id TEXT COLLATE "C" PRIMARY KEY REFERENCES audit_records(audit_id) ON DELETE CASCADE,
    identity_version BIGINT NOT NULL CHECK (identity_version > 0),
    extracted_at_ns BIGINT NOT NULL CHECK (extracted_at_ns > 0),
    source TEXT COLLATE "C" NOT NULL CHECK (source IN
        ('declared', 'codex_turn_metadata', 'agent_header', 'root', 'cwd', 'none')),
    body_scanned BIGINT NOT NULL CHECK (body_scanned IN (0, 1)),
    identity_fpr BYTEA CHECK (identity_fpr IS NULL OR length(identity_fpr) = 32),
    remote_fpr BYTEA CHECK (remote_fpr IS NULL OR length(remote_fpr) = 32),
    repo_root_fpr BYTEA CHECK (repo_root_fpr IS NULL OR length(repo_root_fpr) = 32),
    cwd_fpr BYTEA CHECK (cwd_fpr IS NULL OR length(cwd_fpr) = 32),
    identity_enc BYTEA CHECK (identity_enc IS NULL OR length(identity_enc) > 0),
    CHECK (
        (source = 'none' AND identity_fpr IS NULL AND identity_enc IS NULL
            AND remote_fpr IS NULL AND repo_root_fpr IS NULL AND cwd_fpr IS NULL)
        OR
        (source <> 'none' AND identity_fpr IS NOT NULL AND identity_enc IS NOT NULL)
    )
);

CREATE INDEX audit_project_identity_fpr_idx ON audit_project_identity (identity_fpr)
    WHERE identity_fpr IS NOT NULL;

CREATE INDEX audit_project_identity_version_idx ON audit_project_identity (identity_version);

-- Administrator catalog. Changes persist first, then the service compiles and
-- atomically swaps its snapshot (the content_policy_rules pattern).
CREATE TABLE project_groups (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT COLLATE "C" NOT NULL CHECK (length(name) BETWEEN 1 AND 128),
    enabled BIGINT NOT NULL CHECK (enabled IN (0, 1)),
    created_at_ns BIGINT NOT NULL CHECK (created_at_ns > 0),
    updated_at_ns BIGINT NOT NULL CHECK (updated_at_ns >= created_at_ns)
);

CREATE UNIQUE INDEX project_groups_name_idx ON project_groups (lower(name));

-- group_id NULL is a global project shared by every group. rules is a JSON
-- array of {kind, pattern} validated by the service.
CREATE TABLE projects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT COLLATE "C" NOT NULL CHECK (length(name) BETWEEN 1 AND 128),
    group_id BIGINT REFERENCES project_groups(id) ON DELETE RESTRICT,
    enabled BIGINT NOT NULL CHECK (enabled IN (0, 1)),
    rules TEXT COLLATE "C" NOT NULL CHECK (length(rules) BETWEEN 2 AND 65536),
    created_at_ns BIGINT NOT NULL CHECK (created_at_ns > 0),
    updated_at_ns BIGINT NOT NULL CHECK (updated_at_ns >= created_at_ns)
);

CREATE UNIQUE INDEX projects_scope_name_idx ON projects (COALESCE(group_id, 0), lower(name));

-- One group per NewAPI user.
CREATE TABLE group_members (
    newapi_user_id BIGINT PRIMARY KEY CHECK (newapi_user_id > 0),
    group_id BIGINT NOT NULL REFERENCES project_groups(id) ON DELETE RESTRICT,
    updated_at_ns BIGINT NOT NULL CHECK (updated_at_ns > 0)
);

CREATE INDEX group_members_group_idx ON group_members (group_id);

-- human/service classification by NewAPI user or token; a token entry wins.
CREATE TABLE principal_class (
    kind TEXT COLLATE "C" NOT NULL CHECK (kind IN ('user', 'token')),
    principal_id BIGINT NOT NULL CHECK (principal_id > 0),
    class TEXT COLLATE "C" NOT NULL CHECK (class IN ('human', 'service')),
    updated_at_ns BIGINT NOT NULL CHECK (updated_at_ns > 0),
    PRIMARY KEY (kind, principal_id)
);

-- Frozen weekly snapshots. No foreign key to audits: a snapshot must outlive
-- retention. week_start is the local date of the report week's first day.
CREATE TABLE org_weekly_snapshots (
    week_start TEXT COLLATE "C" PRIMARY KEY CHECK (length(week_start) = 10),
    frozen_at_ns BIGINT NOT NULL CHECK (frozen_at_ns > 0),
    generated_at_ns BIGINT NOT NULL CHECK (generated_at_ns > 0)
);

-- One row per (week, section, user, token, project). project_id 0 is the
-- user's total row, which also carries the per-user figures (concurrency,
-- daily curve, flags); -1 is unattributed and -2 no project context.
-- section 'ranked' rows have token 0; 'service' rows name a service token or
-- 0 for a whole service user.
CREATE TABLE org_weekly_stats (
    week_start TEXT COLLATE "C" NOT NULL REFERENCES org_weekly_snapshots(week_start) ON DELETE CASCADE,
    section TEXT COLLATE "C" NOT NULL CHECK (section IN ('ranked', 'service')),
    newapi_user_id BIGINT NOT NULL CHECK (newapi_user_id >= 0),
    newapi_token_id BIGINT NOT NULL CHECK (newapi_token_id >= 0),
    project_id BIGINT NOT NULL CHECK (project_id >= -2),
    group_id BIGINT NOT NULL CHECK (group_id >= 0),
    project_name TEXT COLLATE "C" NOT NULL DEFAULT '' CHECK (length(project_name) <= 128),
    active_ns BIGINT NOT NULL CHECK (active_ns >= 0),
    other_active_ns BIGINT NOT NULL DEFAULT 0 CHECK (other_active_ns >= 0),
    inferred_ns BIGINT NOT NULL DEFAULT 0 CHECK (inferred_ns >= 0),
    roots BIGINT NOT NULL CHECK (roots >= 0),
    single_request_roots BIGINT NOT NULL DEFAULT 0 CHECK (single_request_roots >= 0),
    requests BIGINT NOT NULL CHECK (requests >= 0),
    identified_requests BIGINT NOT NULL DEFAULT 0 CHECK (identified_requests >= 0),
    billed_requests BIGINT NOT NULL DEFAULT 0 CHECK (billed_requests >= 0),
    u_uncached_input BIGINT NOT NULL CHECK (u_uncached_input >= 0),
    u_cache_read BIGINT NOT NULL CHECK (u_cache_read >= 0),
    u_cache_write BIGINT NOT NULL CHECK (u_cache_write >= 0),
    u_output BIGINT NOT NULL CHECK (u_output >= 0),
    cost_usd DOUBLE PRECISION NOT NULL CHECK (cost_usd >= 0),
    peak_concurrency BIGINT NOT NULL DEFAULT 0 CHECK (peak_concurrency >= 0),
    avg_concurrency DOUBLE PRECISION NOT NULL DEFAULT 0 CHECK (avg_concurrency >= 0),
    daily_active_ns TEXT COLLATE "C" NOT NULL DEFAULT '[]' CHECK (length(daily_active_ns) <= 512),
    flags TEXT COLLATE "C" NOT NULL DEFAULT '[]' CHECK (length(flags) <= 4096),
    PRIMARY KEY (week_start, section, newapi_user_id, newapi_token_id, project_id)
);