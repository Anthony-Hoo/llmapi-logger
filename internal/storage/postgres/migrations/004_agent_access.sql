-- Agent access (doc/features/25-agent-access.md section 4).
-- Management data only: neither table is part of the integrity event chain or
-- copied by the SQLite offline importer. No token, authorization code, API key
-- or key fingerprint of the agent token itself is stored in plaintext:
-- token_mac is HMAC-SHA-256 under a key derived from admin_token, so rotating
-- admin_token makes every row unreachable.

-- One row is one authorized device.
CREATE TABLE agent_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_mac BYTEA NOT NULL UNIQUE CHECK (length(token_mac) = 32),
    display_prefix TEXT COLLATE "C" NOT NULL CHECK (length(display_prefix) BETWEEN 1 AND 16),
    role TEXT COLLATE "C" NOT NULL CHECK (role IN ('admin', 'developer')),
    tier TEXT COLLATE "C" NOT NULL CHECK (tier IN ('read', 'write')),
    device_name TEXT NOT NULL CHECK (length(device_name) BETWEEN 1 AND 64),
    cli_version TEXT COLLATE "C" NOT NULL CHECK (length(cli_version) BETWEEN 1 AND 32),
    -- Developer scope, fixed from the authorizing web session; NULL for
    -- administrator tokens. It mirrors the v2 session cookie payload.
    scope_fingerprint BYTEA CHECK (scope_fingerprint IS NULL OR length(scope_fingerprint) = 32),
    scope_token_id BIGINT CHECK (scope_token_id IS NULL OR scope_token_id >= 0),
    scope_user_id BIGINT,
    scope_username TEXT,
    scope_token_name TEXT,
    created_at_ns BIGINT NOT NULL CHECK (created_at_ns > 0),
    expires_at_ns BIGINT NOT NULL CHECK (expires_at_ns > created_at_ns),
    revoked_at_ns BIGINT,
    last_used_at_ns BIGINT,
    CHECK (
        (role = 'admin' AND scope_fingerprint IS NULL AND scope_token_id IS NULL
            AND scope_user_id IS NULL AND scope_username IS NULL AND scope_token_name IS NULL)
        OR
        (role = 'developer' AND tier = 'read' AND scope_fingerprint IS NOT NULL)
    )
);

CREATE INDEX agent_tokens_scope_idx ON agent_tokens (scope_fingerprint)
    WHERE scope_fingerprint IS NOT NULL;

-- Authorizations, exchanges, revocations, download links, every write and the
-- sensitive reads. Values are never recorded: changed_keys holds key names only.
CREATE TABLE agent_audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    at_ns BIGINT NOT NULL CHECK (at_ns > 0),
    event TEXT COLLATE "C" NOT NULL CHECK (length(event) BETWEEN 1 AND 64),
    token_id BIGINT,
    role TEXT COLLATE "C",
    command TEXT,
    cli_version TEXT,
    object_kind TEXT,
    object_id TEXT,
    changed_keys TEXT,
    outcome TEXT COLLATE "C" NOT NULL CHECK (outcome IN ('ok', 'denied', 'failed')),
    error_code TEXT COLLATE "C"
);

CREATE INDEX agent_audit_log_at_idx ON agent_audit_log (at_ns DESC, id DESC);
